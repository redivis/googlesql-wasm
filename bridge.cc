constexpr uint8_t kStatusOk = 0;
constexpr uint8_t kStatusError = 1;

void* Pack(uint8_t status, absl::string_view payload) {
  const uint32_t size = static_cast<uint32_t>(1 + payload.size());
  auto* buffer = static_cast<uint8_t*>(malloc(sizeof(uint32_t) + size));
  memcpy(buffer, &size, sizeof(uint32_t));
  buffer[sizeof(uint32_t)] = status;
  memcpy(buffer + sizeof(uint32_t) + 1, payload.data(), payload.size());
  return buffer;
}

void* PackError(absl::string_view message) { return Pack(kStatusError, message); }

// Formats an analyzer or parser error on one line, with its location in the SQL
void* PackError(const absl::Status& status, absl::string_view sql) {
  const absl::Status updated = googlesql::MaybeUpdateErrorFromPayload(
      googlesql::ErrorMessageOptions{
          .mode = googlesql::ERROR_MESSAGE_ONE_LINE,
          .attach_error_location_payload = false,
          .stability = googlesql::ERROR_MESSAGE_STABILITY_UNSPECIFIED},
      sql, status);
  return PackError(updated.message());
}

void* PackProto(const google::protobuf::Message& message) {
  std::string serialized;
  if (!message.SerializeToString(&serialized)) {
    return PackError("Failed to serialize the response");
  }
  return Pack(kStatusOk, serialized);
}

// BigQuery's dialect: every released feature, external product mode
googlesql::LanguageOptions DefaultLanguageOptions() {
  googlesql::LanguageOptions language;
  language.EnableMaximumLanguageFeatures();
  language.set_product_mode(googlesql::PRODUCT_EXTERNAL);
  return language;
}

std::vector<const google::protobuf::DescriptorPool*> DescriptorPools() {
  return {google::protobuf::DescriptorPool::generated_pool()};
}


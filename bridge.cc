// The C ABI of the googlesql wasm module. Each call takes a serialized googlesql.local_service request proto and
//   returns a buffer laid out as
//     uint32 size (little endian) | uint8 status | payload
//   where status 0 means the payload is the serialized response proto, and 1 means it's a UTF-8 error message (with the
//   location as "[at line:col]" where known). The caller frees the buffer with googlesql_free().
//
// The requests and responses are the same protos the gRPC local_service uses, so a client written against this module
//   could talk to that server instead. Where a request leaves the language options unset, BigQuery's are used: every
//   released language feature, in external product mode.
